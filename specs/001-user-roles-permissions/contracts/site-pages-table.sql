CREATE TABLE IF NOT EXISTS public.site_pages (
  slug TEXT PRIMARY KEY,
  title TEXT NOT NULL,
  content TEXT NOT NULL,
  updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT NOW()
);

ALTER TABLE public.site_pages ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "site_pages_read_all" ON public.site_pages;
CREATE POLICY "site_pages_read_all" ON public.site_pages
  FOR SELECT
  USING (true);

DROP POLICY IF EXISTS "site_pages_admin_write" ON public.site_pages;
CREATE POLICY "site_pages_admin_write" ON public.site_pages
  FOR UPDATE
  USING (public.is_admin())
  WITH CHECK (public.is_admin());

-- 다른 테이블(announcements 등)과 달리 이 페이지들은 로그인 전(비회원)에게도 공개되어야
-- 하므로(약관은 가입 전에도 볼 수 있어야 함) anon role에도 SELECT를 허용한다.
GRANT SELECT ON public.site_pages TO anon, authenticated;
GRANT UPDATE ON public.site_pages TO authenticated;

